export function getProductById(id) {
  return CRACKERS_DATA.find((c) => c.id === id || c.productId === Number(id))
}

export function getProductsByCategory(category) {
  if (category === 'all') return CRACKERS_DATA
  return CRACKERS_DATA.filter((c) => c.category === category)
}

export function searchProducts(query) {
  const q = query.toLowerCase()
  return CRACKERS_DATA.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      (c.tamilName && c.tamilName.toLowerCase().includes(q)) ||
      c.category.toLowerCase().includes(q) ||
      String(c.sno).includes(q) ||
      c.sku.toLowerCase().includes(q)
  )
}
